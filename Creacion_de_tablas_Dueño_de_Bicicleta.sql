-- 4. FUNCIONES EN ORACLE PL/SQL (3 FUNCIONES)
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_obtener_conteo_accesos (
    p_username IN VARCHAR2
) RETURN NUMBER IS
    v_total NUMBER := 0;
BEGIN
    SELECT total_accesos
      INTO v_total
      FROM bike_usuarios_sistema
     WHERE UPPER(username) = UPPER(p_username);
    RETURN v_total;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
END fn_obtener_conteo_accesos;
/

CREATE OR REPLACE FUNCTION fn_obtener_rol_usuario (
    p_usuario_id IN NUMBER
) RETURN VARCHAR2 IS
    v_rol VARCHAR2(50);
BEGIN
    SELECT r.nombre_rol
      INTO v_rol
      FROM bike_usuarios_sistema u
      JOIN bike_roles_sistema r ON u.rol_id = r.rol_id
     WHERE u.usuario_id = p_usuario_id;
    RETURN v_rol;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'SIN ROL';
END fn_obtener_rol_usuario;
/

CREATE OR REPLACE FUNCTION fn_usuario_esta_activo (
    p_username IN VARCHAR2
) RETURN NUMBER IS
    v_estado VARCHAR2(30);
BEGIN
    SELECT e.nombre_estado
      INTO v_estado
      FROM bike_usuarios_sistema u
      JOIN bike_estados e ON u.id_estado = e.id_estado
     WHERE UPPER(u.username) = UPPER(p_username);

    IF v_estado = 'ACTIVO' THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END fn_usuario_esta_activo;
/

