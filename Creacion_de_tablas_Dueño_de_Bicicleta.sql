CREATE OR REPLACE PROCEDURE sp_insertar_rol_sistema (
    p_nombre_rol  IN  bike_roles_sistema.nombre_rol%TYPE,
    p_descripcion IN  bike_roles_sistema.descripcion%TYPE,
    p_id_estado   IN  bike_roles_sistema.id_estado%TYPE,
    p_mensaje     OUT VARCHAR2
) AS
BEGIN
    INSERT INTO bike_roles_sistema (nombre_rol, descripcion, id_estado)
    VALUES (UPPER(TRIM(p_nombre_rol)), p_descripcion, p_id_estado);
    COMMIT;
    p_mensaje := 'Rol creado correctamente.';
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
