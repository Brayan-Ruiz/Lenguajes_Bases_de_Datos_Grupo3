CREATE OR REPLACE VIEW vw_usuarios_control_acceso AS
SELECT 
    u.usuario_id,
    u.username,
    u.nombre_completo,
    r.nombre_rol,
    NVL(t.nombre_tienda, 'TODAS / CENTRAL') AS tienda_asignada,
    u.ultimo_acceso,
    u.total_accesos,
    u.intentos_fallidos,
    e.nombre_estado AS estado_usuario
FROM bike_usuarios_sistema u
JOIN bike_roles_sistema r ON u.rol_id = r.rol_id
LEFT JOIN bike_tienda t   ON u.tienda_id = t.tienda_id
JOIN bike_estados e       ON u.id_estado = e.id_estado;

CREATE OR REPLACE VIEW vw_estadisticas_acceso_por_rol AS
SELECT 
    r.rol_id,
    r.nombre_rol,
    COUNT(u.usuario_id) AS cantidad_usuarios,
    NVL(SUM(u.total_accesos), 0) AS suma_total_accesos,
    MAX(u.ultimo_acceso) AS acceso_mas_reciente
FROM bike_roles_sistema r
LEFT JOIN bike_usuarios_sistema u ON r.rol_id = u.rol_id
GROUP BY r.rol_id, r.nombre_rol;

CREATE OR REPLACE VIEW vw_bitacora_accesos_detalle AS
SELECT 
    b.bitacora_id,
    u.username,
    u.nombre_completo,
    r.nombre_rol,
    b.fecha_acceso,
    b.estado_intento,
    b.detalle
FROM bike_bitacora_accesos b
JOIN bike_usuarios_sistema u ON b.usuario_id = u.usuario_id
JOIN bike_roles_sistema r    ON u.rol_id = r.rol_id;

