CREATE OR REPLACE PROCEDURE sp_validar_login (
    p_username        IN  bike_usuarios_sistema.username%TYPE,
    p_password        IN  bike_usuarios_sistema.password_hash%TYPE,
    p_usuario_id      OUT bike_usuarios_sistema.usuario_id%TYPE,
    p_nombre_completo OUT bike_usuarios_sistema.nombre_completo%TYPE,
    p_nombre_rol      OUT bike_roles_sistema.nombre_rol%TYPE,
    p_total_accesos   OUT bike_usuarios_sistema.total_accesos%TYPE,
    p_resultado       OUT VARCHAR2
) AS
    v_pass_bd   bike_usuarios_sistema.password_hash%TYPE;
    v_estado    VARCHAR2(30);
BEGIN
    SELECT u.usuario_id, u.password_hash, u.nombre_completo, r.nombre_rol, e.nombre_estado
      INTO p_usuario_id, v_pass_bd, p_nombre_completo, p_nombre_rol, v_estado
      FROM bike_usuarios_sistema u
      JOIN bike_roles_sistema r ON u.rol_id = r.rol_id
      JOIN bike_estados e       ON u.id_estado = e.id_estado
     WHERE LOWER(u.username) = LOWER(TRIM(p_username));

    IF v_estado != 'ACTIVO' THEN
        INSERT INTO bike_bitacora_accesos (usuario_id, estado_intento, detalle)
        VALUES (p_usuario_id, 'DENEGADO', 'Intento de acceso con usuario INACTIVO');
        COMMIT;

        p_usuario_id    := NULL;
        p_nombre_rol    := NULL;
        p_total_accesos := 0;
        p_resultado     := 'ACCESO DENEGADO: El usuario está inactivo.';
        RETURN;
    END IF;

    IF v_pass_bd = p_password THEN
        UPDATE bike_usuarios_sistema
           SET ultimo_acceso     = SYSDATE,
               total_accesos     = total_accesos + 1,
               intentos_fallidos = 0
         WHERE usuario_id = p_usuario_id
         RETURNING total_accesos INTO p_total_accesos;

        INSERT INTO bike_bitacora_accesos (usuario_id, estado_intento, detalle)
        VALUES (p_usuario_id, 'EXITOSO', 'Ingreso correcto al sistema Bike Store');
        COMMIT;

        p_resultado := 'ACCESO CONCEDIDO';
    ELSE
        UPDATE bike_usuarios_sistema
           SET intentos_fallidos = intentos_fallidos + 1
         WHERE usuario_id = p_usuario_id;

        INSERT INTO bike_bitacora_accesos (usuario_id, estado_intento, detalle)
        VALUES (p_usuario_id, 'FALLIDO', 'Contraseña incorrecta');
        COMMIT;

        p_usuario_id    := NULL;
        p_nombre_rol    := NULL;
        p_total_accesos := 0;
        p_resultado     := 'ERROR: Usuario o contraseña incorrectos.';
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_usuario_id      := NULL;
        p_nombre_completo := NULL;
        p_nombre_rol      := NULL;
        p_total_accesos   := 0;
        p_resultado       := 'ERROR: Usuario o contraseña incorrectos.';
    WHEN OTHERS THEN
        ROLLBACK;
        p_resultado := 'ERROR EN EL SISTEMA: ' || SQLERRM;
END sp_validar_login;
/

